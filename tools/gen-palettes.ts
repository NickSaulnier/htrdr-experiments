// Generate src/color/paletteData.ts from the upstream palette sources.
//
//   pnpm tsx tools/gen-palettes.ts <bids_colormaps.py> <colorbrewer.js>
//
// Sources (both are read as text, never executed):
//   - https://raw.githubusercontent.com/BIDS/colormap/master/colormaps.py
//     magma, inferno, plasma, viridis. CC0 / public domain.
//   - https://cdn.jsdelivr.net/npm/colorbrewer@1.5.6/index.js
//     ColorBrewer schemes. Apache-2.0, (c) 2002 Cynthia Brewer, Mark Harrower
//     and The Pennsylvania State University.
//
// star-cmap uses the 8-class variant of every ColorBrewer scheme it ships, so
// we do too. Moreland and jet are computed in palettes.ts instead.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const [bidsPath, brewerPath] = process.argv.slice(2);
if (!bidsPath || !brewerPath) {
  console.error("usage: tsx tools/gen-palettes.ts <bids_colormaps.py> <colorbrewer.js>");
  process.exit(1);
}

const MATPLOTLIB = ["magma", "inferno", "plasma", "viridis"];
const BREWER = [
  "Accent", "Blues", "BrBG", "BuGn", "BuPu", "Dark2", "GnBu", "Greens", "Greys", "Oranges", "OrRd",
  "Paired", "Pastel1", "Pastel2", "PiYG", "PRGn", "PuBu", "PuBuGn", "PuOr", "PuRd", "Purples", "RdBu",
  "RdGy", "RdPu", "RdYlBu", "RdYlGn", "Reds", "Set1", "Set2", "Set3", "Spectral", "YlGn", "YlGnBu",
  "YlOrBr", "YlOrRd",
];
const BREWER_CLASSES = 8;

const hex = (v: number) => Math.round(Math.min(Math.max(v, 0), 1) * 255).toString(16).padStart(2, "0");

function matplotlib(source: string, name: string): string[] {
  const match = new RegExp(`_${name}_data = \\[(.*?)\\]\\]`, "s").exec(source);
  if (!match) throw new Error(`no _${name}_data in ${bidsPath}`);
  const rows = [...match[1]!.matchAll(/\[\s*([\d.e+-]+),\s*([\d.e+-]+),\s*([\d.e+-]+)\s*\]?/g)];
  if (rows.length !== 256) throw new Error(`${name}: expected 256 colors, found ${rows.length}`);
  return rows.map((m) => `#${hex(Number(m[1]))}${hex(Number(m[2]))}${hex(Number(m[3]))}`);
}

function brewer(source: string, name: string): string[] {
  const block = new RegExp(`\\b${name}: \\{(.*?)\\}`, "s").exec(source);
  if (!block) throw new Error(`no ${name} scheme in ${brewerPath}`);
  const row = new RegExp(`\\b${BREWER_CLASSES}: \\[([^\\]]*)\\]`).exec(block[1]!);
  if (!row) throw new Error(`${name} has no ${BREWER_CLASSES}-class variant`);
  const colors = [...row[1]!.matchAll(/"(#[0-9a-f]{6})"/gi)].map((m) => m[1]!.toLowerCase());
  if (colors.length !== BREWER_CLASSES) throw new Error(`${name}: expected ${BREWER_CLASSES} colors`);
  return colors;
}

const bids = readFileSync(bidsPath, "utf8");
const brewerSource = readFileSync(brewerPath, "utf8");
const entries: [string, string[]][] = [
  ...MATPLOTLIB.map((n): [string, string[]] => [n, matplotlib(bids, n)]),
  ...BREWER.map((n): [string, string[]] => [n.toLowerCase(), brewer(brewerSource, n)]),
].sort(([a], [b]) => a.localeCompare(b));

const body = entries
  .map(([name, colors]) => {
    const lines: string[] = [];
    for (let i = 0; i < colors.length; i += 8) lines.push(`    ${colors.slice(i, i + 8).map((c) => `"${c}"`).join(", ")},`);
    return `  ${name}: [\n${lines.join("\n")}\n  ],`;
  })
  .join("\n");

const out = `// Generated by tools/gen-palettes.ts; do not edit.
//
// magma, inferno, plasma, viridis: Nathaniel J. Smith, Stefan van der Walt and
// Eric Firing (BIDS/colormap), released under CC0.
// All others: ColorBrewer, (c) 2002 Cynthia Brewer, Mark Harrower and The
// Pennsylvania State University, Apache License 2.0.

export const PALETTE_DATA: Record<string, readonly string[]> = {
${body}
};
`;

const target = join(import.meta.dirname, "..", "src", "color", "paletteData.ts");
writeFileSync(target, out);
console.log(`wrote ${entries.length} palettes to src/color/paletteData.ts`);
